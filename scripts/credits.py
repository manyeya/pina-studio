#!/usr/bin/env python3
"""The open-source software in this app, from Cargo's own record of it (Cargo.lock), written to
crates/app/src/credits.rs for the About page: every crate a build for macOS, Windows or the web
uses or is built with, its version, licence, home and authors. The app's own crates and its
author's other work (Pina Studio's engine) are left out: they're credited by name.

Run it again whenever a dependency changes:

    scripts/credits.py "Pina Live"

A test (credits_match_cargo_lock) fails when it's out of date.
"""

import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
APP = sys.argv[1] if len(sys.argv) > 1 else ROOT.name
OUT = ROOT / "crates" / "app" / "src" / "credits.rs"
OWN = "github.com/manyeya/"


def rust(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def people(authors: list[str]) -> str:
    # Names only: an author's email isn't for an About page.
    names = [re.sub(r"\s*<[^>]*>", "", a).strip() for a in authors]
    names = [n for n in names if n]
    return ", ".join(names[:3]) + (" and others" if len(names) > 3 else "")


# The platforms it ships on: a Linux-only crate is in none of its builds.
TARGETS = ["aarch64-apple-darwin", "x86_64-apple-darwin", "x86_64-pc-windows-msvc", "wasm32-unknown-unknown"]

packages, seen, members = {}, set(), set()
for target in TARGETS:
    meta = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
            cwd=ROOT,
        )
    )
    packages.update({p["id"]: p for p in meta["packages"]})
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    members = set(meta["workspace_members"])
    # Everything reachable from the app's own crates, but not by their dev-dependencies (tests).
    todo = list(members)
    while todo:
        for dep in nodes[todo.pop()]["deps"]:
            if any(k["kind"] != "dev" for k in dep["dep_kinds"]) and dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                todo.append(dep["pkg"])

crates = {}
for pid in seen:
    p = packages[pid]
    if pid in members or OWN in (p.get("source") or ""):
        continue
    license = p.get("license") or ("See its licence file" if p.get("license_file") else "Unstated")
    url = p.get("repository") or p.get("homepage") or f"https://crates.io/crates/{p['name']}"
    crates[(p["name"], p["version"])] = (license, url, people(p.get("authors") or []))

lines = [
    "// Generated by scripts/credits.py from Cargo.lock: don't edit it, run that again.",
    f"//! Every open-source crate in {APP} (any of its builds) or used to build it: its version,",
    "//! licence, home and authors. The About page lists them all.",
    "",
    "pub struct Crate {",
    "    pub name: &'static str,",
    "    pub version: &'static str,",
    "    pub license: &'static str,",
    "    pub url: &'static str,",
    "    pub by: &'static str,",
    "}",
    "",
    "pub const CRATES: &[Crate] = &[",
]
for (name, version), (license, url, by) in sorted(crates.items(), key=lambda kv: (kv[0][0].lower(), kv[0][1])):
    lines.append(
        f"    Crate {{ name: {rust(name)}, version: {rust(version)}, license: {rust(license)}, "
        f"url: {rust(url)}, by: {rust(by)} }},"
    )
lines.append("];")
OUT.write_text("\n".join(lines) + "\n")
print(f"{len(crates)} crates -> {OUT.relative_to(ROOT)}")
